def parse_datetime(date_str: str) -> str:
    """Парсит 'DD.MM.YYYY, HH:MM' в ISO-8601."""
    try:
        dt = datetime.strptime(date_str.strip(), '%d.%m.%Y, %H:%M')
        return dt.strftime('%Y-%m-%dT%H:%M:%S+00:00')
    except ValueError:
        return ''


def parse_line(line: str):
    """Парсит одну строку дампа. Возвращает dict или None."""
    line = line.strip()
    if not line:
        return None

    # 1. Дата
    m = re.match(r'^(\d{2}\.\d{2}\.\d{4},\s*\d{2}:\d{2})', line)
    if not m:
        return None
    date_str = m.group(1)
    rest = line[m.end():]

    created_at = parse_datetime(date_str)
    if not created_at:
        return None

    # 2. Статус/этап
    stage_m = re.search(r'(Прошел тест|Открыл тест|Не начал|Записался ✓|💰 Покупка)', rest)
    if not stage_m:
        return None
    stage = stage_m.group(1)
    before_stage = rest[:stage_m.start()]

    # 3. UTM-источник — ищем в хвосте после статуса
    utm = 'Нет данных'
    after_stage = rest[stage_m.end():]
    for u in KNOWN_UTMS:
        if u in after_stage:
            utm = u
            break

    # 4. Балл/уровень: X/10 (Название)
    score_m = re.search(r'(\d+)/10\s*\(([^)]+)\)', rest)
    score = int(score_m.group(1)) if score_m else 0
    diagnosis = score_m.group(2) if score_m else ''

    # 5. Идентификатор: @username или telegram_id или токен сессии
    ident = before_stage.strip().rstrip('—').rstrip('💰')
    # Чистим дубли (пример: @user@user → @user)
    if ident.startswith('@'):
        ident = '@' + ident[1:].split('@')[0]
    # Чистим мусор от склеенных статусов
    for suffix in ['Записался ✓Созвон', '💰 ПокупкаПокупка', '💰 Покупка']:
        if suffix in ident:
            ident = ident[:ident.index(suffix)]

    telegram_id = ''
    name = ''
    if ident.startswith('@'):
        name = ident  # сохраняем как есть, с @
    elif ident.isdigit():
        telegram_id = ident
    elif ident:
        # Всё остальное (токены вида XxxYYYzzz и т.д.) — сохраняем как telegram_id
        telegram_id = ident

    # 6. Маппинг статуса в test_type признак
    # «Прошел тест» = completed; остальное не пишем как результат (только completed)
    if stage != 'Прошел тест':
        # Для не-завершённых мы не создаём запись test_results,
        # но считаем статистику. Пока импортируем только completed.
        return None

    return {
        'created_at': created_at,
        'telegram_id': telegram_id,
        'name': name,
        'test_type': 'mens',
        'total_score': score,
        'diagnosis': diagnosis,
        'utm_source': utm,
    }


